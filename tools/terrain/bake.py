"""Bakes a region's terrain module (e.g. campaign/core/dem-bend.js) from the committed source crop.

Usage: python3 tools/terrain/bake.py REGION        (needs numpy, scipy, pillow)
Output: size x size heights (uint8 metres above `base`, base64), a river bitset and the river centre line.
Steps: project the crop onto the game grid (config `projection`, `grid`), trace the river as the least-cost path along
the valley floor between the configured edge areas, mark water where a cell is within `maxDist` units of the path and
at most `aboveLevel` m above the smoothed, downstream-monotone river level, simplify the path to a polyline.
"""
import base64, heapq, json, os, sys
import numpy as np
from scipy.ndimage import gaussian_filter, gaussian_filter1d, distance_transform_edt
import terrain_lib as T


def river_path(G, X, Z, rc, R):
    inside = X ** 2 + Z ** 2 < R * R
    def edge_min(cond):
        idx = np.argwhere(cond)
        if not len(idx): sys.exit('river start / goal area is empty - check the region config')
        return tuple(idx[int(np.argmin([G[r, c] for r, c in idx]))])
    s, g = rc['start'], rc['goal']
    start = edge_min((Z < s['zBelow']) & (np.abs(X - s['xNear']) < s['xWithin']) & inside)
    xside = (X > g['xAbove']) if 'xAbove' in g else (X < g['xBelow'])
    goal = edge_min((Z > g['zAbove']) & xside & inside & (X ** 2 + Z ** 2 > g['minRadius'] ** 2))
    cost = np.exp((G - G.min()) / rc['costScale'])
    N = G.shape[0]
    dist = np.full(G.shape, np.inf); prev = {}; dist[start] = 0; pq = [(0, start)]
    while pq:
        d, u = heapq.heappop(pq)
        if u == goal: break
        if d > dist[u]: continue
        for dr in (-1, 0, 1):
            for dc in (-1, 0, 1):
                if dr == dc == 0: continue
                v = (u[0] + dr, u[1] + dc)
                if not (0 <= v[0] < N and 0 <= v[1] < N): continue
                nd = d + cost[v] * (1.414 if dr and dc else 1)
                if nd < dist[v]: dist[v] = nd; prev[v] = u; heapq.heappush(pq, (nd, v))
    path = [goal]
    while path[-1] != start: path.append(prev[path[-1]])
    return np.array(path[::-1])


def water(G, path, rc, cell):
    pr, pc = path[:, 0], path[:, 1]
    lvl = np.minimum.accumulate(gaussian_filter(G[pr, pc], 3))
    mask = np.zeros(G.shape, bool); mask[pr, pc] = True
    d, ind = distance_transform_edt(~mask, return_indices=True)
    idx = np.full(G.shape, -1); idx[pr, pc] = np.arange(len(path))
    return (d * cell < rc['maxDist']) & (G <= lvl[idx[ind[0], ind[1]]] + rc['aboveLevel'])


def rdp(pts, eps):
    if len(pts) < 3: return pts
    a, b = pts[0], pts[-1]; ab = b - a; q = pts - a
    d = np.abs(ab[0] * q[:, 1] - ab[1] * q[:, 0]) / np.hypot(*ab)
    i = int(np.argmax(d))
    return np.vstack([rdp(pts[:i + 1], eps)[:-1], rdp(pts[i:], eps)]) if d[i] > eps else np.array([a, b])


def bake(rid):
    cfg = T.region(rid); H, m = T.load_crop(rid)
    g, rc, p = cfg['grid'], cfg['river'], cfg['projection']
    xs, X, Z, G = T.grid(cfg, H, m)
    path = river_path(G, X, Z, rc, g['radius'])
    W = water(G, path, rc, g['cell'])
    P = np.array([[xs[c], xs[r]] for r, c in path], float)
    P = np.stack([gaussian_filter1d(P[:, 0], rc['smooth']), gaussian_filter1d(P[:, 1], rc['smooth'])], 1)
    poly = (np.round(rdp(P, rc['simplify']) / 5) * 5).astype(int).tolist()
    return cfg, m, G, W, poly


TPL = """/*
 * Verdigris campaign - baked terrain of the %(title)s. GENERATED by tools/terrain/bake.py %(id)s, do not edit
 * (config tools/terrain/regions/%(id)s.json, source tools/terrain/sources/%(id)s_dtm.png).
 * Source: %(source)s.
 * Licence: %(licence)s.
 * Projection around %(lon0)s E, %(lat0)s N at %(mpu)s m per unit, +X = west, +Z = north (the game's axes:
 * facing north, +X is on the left; the compass says W toward +X).
 *   size x size samples, `cell` units apart, x and z from -radius to +radius (row = z, column = x);
 *   h: base64 Uint8, metres above `base` (1 m steps); water: base64 bitset (row-major, MSB first), 1 = river;
 *   river: centre line polyline (units) in flow direction.
 */
(function (root) {
  'use strict';
  const M = typeof module === 'object' && module.exports ? require('./umd.js') : root.VCamp;
  M.define('%(module)s', {
    size: %(size)d, cell: %(cell)d, radius: %(radius)d, base: %(base)d, metresPerUnit: %(mpu)s,
    river: %(river)s,
    h: '%(h)s',
    water: '%(water)s',
  });
})(typeof window !== 'undefined' ? window : globalThis);
"""


def main(rid):
    cfg, m, G, W, poly = bake(rid)
    g, p = cfg['grid'], cfg['projection']
    out = os.path.join(T.ROOT, cfg['out'])
    open(out, 'w').write(TPL % {
        'title': cfg['title'], 'id': rid, 'module': cfg['module'], 'source': m['source'], 'licence': m['licence'],
        'lon0': p['lon0'], 'lat0': p['lat0'], 'mpu': p['metresPerUnit'], 'size': G.shape[0], 'cell': g['cell'],
        'radius': g['radius'], 'base': g['base'], 'river': json.dumps(poly),
        'h': base64.b64encode(np.clip(np.round(G - g['base']), 0, 255).astype(np.uint8).tobytes()).decode(),
        'water': base64.b64encode(np.packbits(W.astype(np.uint8).ravel()).tobytes()).decode()})
    print('wrote', cfg['out'], 'river points', len(poly), 'water cells', int(W.sum()),
          'heights', round(G.min(), 1), '-', round(G.max(), 1), 'm')


if __name__ == '__main__':
    main(sys.argv[1])
